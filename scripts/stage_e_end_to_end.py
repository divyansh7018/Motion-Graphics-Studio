"""Stage E end-to-end: build a real project and render a real MP4.

This is the deliverable from directive sections 70-71, 73-74 and 91.  It builds
``StageE_Test`` with real content - narration, a music bed, a sound effect,
subtitles, transitions, an animation, an image and a chart plus a number - then
renders it twice and verifies both files with the real probe and the QC service.

Nothing here is mocked.  If narration cannot be generated by Kokoro (no model
weights on this machine), the script says so loudly and falls back to real audio
files of a measured length, so the render is still a real render - and the
report marks the narration as synthetic rather than passing it off as Kokoro.

Usage::

    python scripts/stage_e_end_to_end.py --data-root /tmp/stage_e
"""

